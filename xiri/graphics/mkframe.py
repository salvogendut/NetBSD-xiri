#!/usr/bin/env python3
"""Compile the supplied console PNG into palette entries and filled rectangles.

Requires Pillow only when regenerating the checked-in header, not when building
the kernel.  Colours are preserved exactly; the text panel must be uniform.
"""

import argparse
import hashlib
from pathlib import Path

from PIL import Image


def generate(source):
    image = Image.open(source).convert("RGB")
    if image.size != (1282, 1024):
        raise ValueError("the frame layout requires a 1282x1024 source image")
    # This inset is deliberately aligned for the console's 8x16 bitmap font.
    x, y, width, height = 288, 176, 704, 672
    panel = image.getpixel((x, y))
    if image.crop((x, y, x + width, y + height)).getextrema() != tuple(
        (c, c) for c in panel
    ):
        raise ValueError("the text area must have a uniform background")

    # Allow 32 terminal/cursor entries and one inverse panel entry.  Other
    # image colours never appear under the cursor and need no inverse entry.
    colours = image.getcolors(223)
    if colours is None:
        raise ValueError("the source uses more than 223 colours")
    colours = sorted(colour for frequency, colour in colours)
    count = len(colours)
    indices = {colour: index for index, colour in enumerate(colours)}
    rgb = image.tobytes()
    pixels = bytes(indices[tuple(rgb[i:i + 3])]
                   for i in range(0, len(rgb), 3))
    panel_index = indices[panel]

    # Merge identical horizontal runs on consecutive scanlines.  Rectangles
    # are disjoint, so repainting them cannot damage neighbours or margins.
    rectangles = []
    active = {}
    for row in range(image.height):
        current = {}
        left = 0
        while left < image.width:
            colour = pixels[row * image.width + left]
            right = left + 1
            while (right < image.width and
                   pixels[row * image.width + right] == colour):
                right += 1
            key = (left, right - left, colour)
            rect = active.pop(key, [left, row, right - left, 0, colour])
            rect[3] += 1
            current[key] = rect
            left = right
        rectangles.extend(active.values())
        active = current
    rectangles.extend(active.values())

    # Check the compressed representation against every source pixel.
    decoded = bytearray(image.width * image.height)
    covered = 0
    for left, top, wi, he, colour in rectangles:
        covered += wi * he
        for row in range(top, top + he):
            start = row * image.width + left
            decoded[start:start + wi] = bytes([colour]) * wi
    if covered != len(pixels) or decoded != pixels:
        raise ValueError("rectangle encoding failed to reproduce the image")

    digest = hashlib.sha256(source.read_bytes()).hexdigest()
    lines = [
        "/* Generated by xiri/graphics/mkframe.py; do not edit. */",
        f"/* Source SHA256: {digest} */",
        "#define NEWPORT_FRAME_WIDTH\t1282",
        "#define NEWPORT_FRAME_HEIGHT\t1024",
        f"#define NEWPORT_FRAME_COLOURS\t{count}",
        f"#define NEWPORT_FRAME_PANEL\t{panel_index}",
        f"#define NEWPORT_FRAME_TEXT_X\t{x}",
        f"#define NEWPORT_FRAME_TEXT_Y\t{y}",
        f"#define NEWPORT_FRAME_TEXT_WIDTH\t{width}",
        f"#define NEWPORT_FRAME_TEXT_HEIGHT\t{height}",
        "",
        "static const uint8_t newport_frame_cmap[NEWPORT_FRAME_COLOURS][3] = {",
    ]
    for r, g, b in colours:
        lines.append(f"\t{{ {r}, {g}, {b} }},")
    lines += [
        "};", "",
        "static const struct newport_frame_rect {",
        "\tuint16_t x, y, width, height;",
        "\tuint8_t colour;",
        "} newport_frame_rects[] = {",
    ]
    for rect in rectangles:
        lines.append("\t{ " + ", ".join(str(v) for v in rect) + " },")
    lines += ["};", ""]
    return "\n".join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    here = Path(__file__).resolve().parent
    output = here.parent.parent / "sys/arch/sgimips/gio/newport_frame.h"
    generated = generate(here / "sgiconsole.png")
    if args.check:
        if output.read_text() != generated:
            raise SystemExit("newport_frame.h needs regeneration")
        print("newport_frame.h matches the source image")
    else:
        output.write_text(generated)


if __name__ == "__main__":
    main()
